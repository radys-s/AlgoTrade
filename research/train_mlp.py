"""Train a small MLP forecaster on an exported signal dataset (Colab GPU or local CPU) and print numpy-ready weights.

On Colab: upload this file and the dataset npz written by `research.signals` (export), then
    !pip install torch numpy   # usually already there
    !python train_mlp.py dataset.npz --hidden 32 --epochs 20 --out mlp_weights.py
Locally (torch is not a project dependency): `uv run --with torch python -m research.train_mlp data/features/X_dataset.npz`

The split is by time, never shuffled across it: the first `--train` fraction trains, the next
`--valid` fraction picks the epoch, the rest is reported as untouched test. The output file holds
plain Python lists (weights, feature means and scales) plus `mlp_predict`, a numpy forward pass
that a strategy can paste in verbatim: no torch, no files, no base64 in the submission.
"""

from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np


def load_dataset(path: Path) -> tuple[np.ndarray, np.ndarray, list[str]]:
    """Features, labels and feature names from an npz; tolerant to the exact key names."""
    data = np.load(path, allow_pickle=False)
    keys = set(data.files)
    x_key = next(key for key in ('X', 'x', 'features') if key in keys)
    y_key = next(key for key in ('y', 'Y', 'label', 'labels', 'target') if key in keys)
    name_key = next((key for key in ('feature_names', 'names', 'columns') if key in keys), None)
    x = data[x_key].astype(np.float32)
    y = data[y_key].astype(np.float32).reshape(-1)
    names = [str(name) for name in data[name_key]] if name_key else [f'f{i}' for i in range(x.shape[1])]
    keep = np.isfinite(x).all(axis=1) & np.isfinite(y)
    return x[keep], y[keep], names


def information_coefficient(prediction: np.ndarray, target: np.ndarray) -> float:
    """Pearson correlation of forecast and outcome, the number that matters for skewing quotes."""
    if prediction.std() == 0 or target.std() == 0:
        return 0.0
    return float(np.corrcoef(prediction, target)[0, 1])


def numpy_module(weights: list[tuple[np.ndarray, np.ndarray]], mean: np.ndarray, scale: np.ndarray, names: list[str]) -> str:
    """Python source with the weights as lists and a numpy forward pass, ready to paste into a strategy."""

    def as_list(array: np.ndarray) -> str:
        return repr(np.round(array.astype(np.float64), 6).tolist())

    lines = [
        '# Generated by research/train_mlp.py: paste into the strategy file.',
        f'MLP_FEATURES = {names!r}',
        f'MLP_MEAN = {as_list(mean)}',
        f'MLP_SCALE = {as_list(scale)}',
        'MLP_LAYERS = [',
    ]
    lines += [f'    ({as_list(w)}, {as_list(b)}),' for w, b in weights]
    lines += [
        ']',
        '',
        '',
        'def mlp_compile():',
        '    """Turn the lists into numpy arrays once, in the strategy __init__."""',
        '    mean = np.array(MLP_MEAN)',
        '    scale = np.array(MLP_SCALE)',
        '    layers = [(np.array(w), np.array(b)) for w, b in MLP_LAYERS]',
        '    return mean, scale, layers',
        '',
        '',
        'def mlp_predict(x, mean, scale, layers):',
        '    """Forecast for one feature vector `x` (same order as MLP_FEATURES); ReLU hidden layers."""',
        '    h = (np.asarray(x, dtype=float) - mean) / scale',
        '    for w, b in layers[:-1]:',
        '        h = np.maximum(h @ w + b, 0.0)',
        '    w, b = layers[-1]',
        '    return float((h @ w + b)[0])',
    ]
    return '\n'.join(lines) + '\n'


def parse_args() -> argparse.Namespace:
    """Parse the command line."""
    parser = argparse.ArgumentParser(description='Train a small MLP on an exported dataset, export numpy weights')
    parser.add_argument('dataset', type=Path)
    parser.add_argument('--hidden', type=int, nargs='+', default=[32], help='Hidden layer sizes')
    parser.add_argument('--epochs', type=int, default=20)
    parser.add_argument('--batch', type=int, default=4096)
    parser.add_argument('--lr', type=float, default=1e-3)
    parser.add_argument('--weight-decay', type=float, default=1e-4)
    parser.add_argument('--train', type=float, default=0.6)
    parser.add_argument('--valid', type=float, default=0.2)
    parser.add_argument('--clip', type=float, default=5.0, help='Clip standardized labels to +-clip (fat tails)')
    parser.add_argument('--out', type=Path, default=Path('mlp_weights.py'))
    return parser.parse_args()


def main() -> None:
    """Time-split, standardize on train only, train with early stopping on valid IC, export."""
    import torch
    from torch import nn

    args = parse_args()
    x, y, names = load_dataset(args.dataset)
    n = len(y)
    train_end, valid_end = int(n * args.train), int(n * (args.train + args.valid))
    mean = x[:train_end].mean(axis=0)
    scale = x[:train_end].std(axis=0)
    scale[scale == 0] = 1.0
    y_scale = float(y[:train_end].std()) or 1.0
    xs = (x - mean) / scale
    ys = np.clip(y / y_scale, -args.clip, args.clip)
    device = 'cuda' if torch.cuda.is_available() else 'cpu'
    print(f'{n} rows, {x.shape[1]} features, device={device}; train/valid/test = {train_end}/{valid_end - train_end}/{n - valid_end}')

    sizes = [x.shape[1], *args.hidden, 1]
    layers: list[nn.Module] = []
    for index, (size_in, size_out) in enumerate(zip(sizes[:-1], sizes[1:], strict=True)):
        layers.append(nn.Linear(size_in, size_out))
        if index < len(sizes) - 2:
            layers.append(nn.ReLU())
    model = nn.Sequential(*layers).to(device)
    optimizer = torch.optim.AdamW(model.parameters(), lr=args.lr, weight_decay=args.weight_decay)
    tensor_x = torch.tensor(xs, device=device)
    tensor_y = torch.tensor(ys, device=device)

    def predict(start: int, end: int) -> np.ndarray:
        model.eval()
        with torch.no_grad():
            return model(tensor_x[start:end]).squeeze(1).cpu().numpy()

    best_ic, best_state = -1.0, None
    for epoch in range(args.epochs):
        model.train()
        order = torch.randperm(train_end, device=device)  # shuffling inside the training window only
        for batch_start in range(0, train_end, args.batch):
            batch = order[batch_start : batch_start + args.batch]
            loss = nn.functional.mse_loss(model(tensor_x[batch]).squeeze(1), tensor_y[batch])
            optimizer.zero_grad()
            loss.backward()
            optimizer.step()
        valid_ic = information_coefficient(predict(train_end, valid_end), y[train_end:valid_end])
        print(f'epoch {epoch + 1:>3}: valid IC {valid_ic:+.4f}')
        if valid_ic > best_ic:
            best_ic = valid_ic
            best_state = {key: value.detach().clone() for key, value in model.state_dict().items()}
    if best_state is not None:
        model.load_state_dict(best_state)

    test_ic = information_coefficient(predict(valid_end, n), y[valid_end:])
    train_ic = information_coefficient(predict(0, train_end), y[:train_end])
    print(f'IC train {train_ic:+.4f}  valid {best_ic:+.4f}  test {test_ic:+.4f}  (test is the honest number)')

    linears = [module for module in model if isinstance(module, nn.Linear)]
    weights = [(layer.weight.detach().cpu().numpy().T, layer.bias.detach().cpu().numpy()) for layer in linears]
    last_w, last_b = weights[-1]
    weights[-1] = (last_w * y_scale, last_b * y_scale)  # undo label scaling: output is in label units (ticks)
    source = numpy_module(weights, mean, scale, names)
    args.out.write_text(source)
    print(f'wrote {args.out} ({len(source) / 1024:.0f} KiB; submission limit is 1 MiB)')


if __name__ == '__main__':
    main()
